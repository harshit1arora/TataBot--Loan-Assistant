"""Sanction letter generation (idempotent per application)."""
from __future__ import annotations

from datetime import UTC, datetime
from io import BytesIO

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from sqlalchemy.orm import Session

from ..config import Settings
from ..errors import ConflictError, NotFoundError
from ..models import Application, Customer, Document
from ..money import format_inr
from ..services import audit, documents, underwriting
from ..storage import ObjectStore


def _render_pdf(
    *, customer: Customer, application: Application, emi_paise: int, rate: float, policy_version: str
) -> bytes:
    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4
    margin = 20 * mm

    pdf.setFont("Helvetica-Bold", 16)
    pdf.drawString(margin, height - margin, "Loan Sanction Letter")
    pdf.setFont("Helvetica", 9)
    pdf.drawString(margin, height - margin - 6 * mm, "SIMULATED DOCUMENT - NOT A CREDIT OFFER")

    y = height - margin - 20 * mm
    lines = [
        ("Date", datetime.now(UTC).astimezone().strftime("%d/%m/%Y")),
        ("Customer", f"{customer.name} ({customer.id})"),
        ("City", customer.city),
        ("Application", application.id),
        ("Approved amount", f"INR {format_inr(application.requested_amount_paise)}"),
        ("Tenure", f"{application.tenure_months} months"),
        ("Interest rate", f"{rate:.2f}% p.a. (reducing balance)"),
        ("EMI", f"INR {format_inr(emi_paise)}"),
        ("Policy version", policy_version),
    ]
    for label, value in lines:
        pdf.setFont("Helvetica-Bold", 10)
        pdf.drawString(margin, y, f"{label}:")
        pdf.setFont("Helvetica", 10)
        pdf.drawString(margin + 45 * mm, y, str(value))
        y -= 8 * mm

    y -= 6 * mm
    pdf.setFont("Helvetica-Oblique", 8)
    for paragraph in [
        "This letter is generated by a demonstration system. It creates no legal",
        "obligation, has not been reviewed by a credit officer, and must not be used",
        "to represent a lending commitment. Disbursal requires separate authorisation.",
    ]:
        pdf.drawString(margin, y, paragraph)
        y -= 5 * mm

    pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def generate(
    db: Session, *, settings: Settings, store: ObjectStore, application: Application
) -> Document:
    """Idempotent: returns the existing letter if one was already issued."""
    existing = documents.sanction_letter_for(db, application.id)
    if existing is not None:
        return existing

    decision = underwriting.latest_decision(db, application.id)
    if decision is None:
        raise ConflictError("No underwriting decision exists for this application.")
    if decision.outcome != "approve" or decision.emi_paise is None:
        raise ConflictError("A sanction letter can only be issued for an approved application.")

    customer = db.get(Customer, application.customer_id)
    if customer is None:
        raise NotFoundError("Customer not found.")

    data = _render_pdf(
        customer=customer,
        application=application,
        emi_paise=decision.emi_paise,
        rate=decision.interest_rate_percent,
        policy_version=decision.policy_version,
    )
    stored = store.save(customer.id, "application/pdf", data)

    letter = Document(
        customer_id=customer.id,
        application_id=application.id,
        doc_type="sanction_letter",
        original_filename=f"sanction_{application.id}.pdf",
        content_type="application/pdf",
        size_bytes=stored.size_bytes,
        sha256=stored.sha256,
        storage_key=stored.key,
        status="issued",
    )
    db.add(letter)
    application.status = "sanctioned"
    db.flush()

    audit.record(
        db,
        actor_type="system",
        actor_id="sanction",
        action="sanction.issued",
        entity_type="application",
        entity_id=application.id,
        metadata={"document_id": letter.id, "emi_paise": decision.emi_paise},
    )
    return letter
